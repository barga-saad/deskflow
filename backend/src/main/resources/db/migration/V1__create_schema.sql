CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    full_name     VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('CUSTOMER', 'AGENT', 'ADMIN')),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE tickets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(160)  NOT NULL,
    description  VARCHAR(5000) NOT NULL,
    status       VARCHAR(20)   NOT NULL CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    priority     VARCHAR(20)   NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    category     VARCHAR(20)   NOT NULL CHECK (category IN ('BILLING', 'TECHNICAL', 'ACCOUNT', 'GENERAL')),
    triage_note  VARCHAR(300),
    triaged_by_ai BOOLEAN      NOT NULL DEFAULT FALSE,
    requester_id BIGINT        NOT NULL REFERENCES users (id),
    assignee_id  BIGINT        REFERENCES users (id),
    due_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at  TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    version      BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX idx_tickets_status ON tickets (status);
CREATE INDEX idx_tickets_requester ON tickets (requester_id);
CREATE INDEX idx_tickets_assignee ON tickets (assignee_id);
CREATE INDEX idx_tickets_due_at ON tickets (due_at);

CREATE TABLE ticket_comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT        NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    author_id  BIGINT        NOT NULL REFERENCES users (id),
    body       VARCHAR(5000) NOT NULL,
    internal   BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_comments_ticket ON ticket_comments (ticket_id);

CREATE TABLE ticket_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT       NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    actor_id   BIGINT       NOT NULL REFERENCES users (id),
    type       VARCHAR(30)  NOT NULL,
    detail     VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_events_ticket ON ticket_events (ticket_id);
